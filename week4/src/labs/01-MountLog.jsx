// 01-MountLog.jsx — Дасгал 1: Хоосон хамаарлын массив
// Зорилго (унших материалын "Дадлага 1"): хоосон массивтай эффект бичиж,
// компонент дэлгэцэнд гарахад НЭГ УДАА мэдэгдэл хэвлэх. Дараа нь товчлуураар
// төлөв сольж, эффект ДАХИН АЖИЛЛАХГҮЙ байгааг батлах.
//
// Хамрах сэдэв: useEffect-ийн синтакс, хоосон хамаарлын массив [],
// анхны дүрслэл (mount), StrictMode-ийн давхар ажиллагаа.

// import — react багцаас зөвхөн хэрэгтэй hook-уудаа нэрээр нь авна.
//   useState — төлөв (өөрчлөгдөх утга) хадгалах,
//   useEffect — дүрслэл дууссаны дараа ажиллах гаж нөлөө (side effect) бичих.
import { useEffect, useState } from 'react'

// Компонент — ТОМ үсгээр эхэлсэн нэртэй, JSX буцаадаг энгийн функц.
export default function MountLog() {
  // count — товч дарах бүрд нэмэгдэх төлөв. Энэ нь дүрслэлийг ДАХИН дуудна
  // (төлөв өөрчлөгдөх бүрд React компонентийг шинээр дуудна = re-render).
  const [count, setCount] = useState(0)

  // logs — дэлгэцэн дээр харах бүртгэлийн жагсаалт. Эффект ажилласан бүрд
  // энэ жагсаалтад шинэ мөр нэмэгдэнэ. (Console-оос гадна нүдээр харах
  // боломжтой болгохын тулд төлөвт хадгалж байна.)
  const [logs, setLogs] = useState([])

  // useEffect(функц, хамаарлынМассив) — 2 аргументтай:
  //   1-р аргумент: дүрслэл дууссаны ДАРАА ажиллах функц,
  //   2-р аргумент: ХООСОН массив [].
  //
  // ХООСОН МАССИВИЙН УТГА: "энэ эффект зөвхөн АНХНЫ дүрслэл дээр нэг удаа
  // ажиллана". React дараагийн дүрслэлүүд дээр харьцуулах утга байхгүй тул
  // эффектийг давтахгүй.
  useEffect(() => {
    // Дүрслэл дууссаны дараа ажиллах ажил. Энэ нь "гаж нөлөө":
    // console болон төлөв нь компонентын гадна орших зүйлс.
    console.log('Анхны дүрслэл дээр нэг удаа ажиллалаа')

    // Бүртгэлийн жагсаалтад шинэ мөр нэмнэ.
    // Функциональ шинэчлэл: prev нь өмнөх жагсаалт; spread (...) нь
    // хуучин мөрүүдийг хуулж, төгсгөлд нь шинэ мөрийг нэмсэн ШИНЭ массив үүсгэнэ.
    //   Хуучин массивт push хийж болохгүй — React өөрчлөлтийг мэдэхгүй.
    setLogs((prev) => [...prev, `Эффект ажиллалаа (${prev.length + 1}-р удаа)`])

    // ЯАГААД ХОЁР МӨР ГАРАХ ВЭ? Хөгжүүлэлтийн горимд StrictMode (main.jsx)
    // эффектийг зориуд 2 удаа ажиллуулж, цэвэрлэгээгээ шалгадаг. Энэ бол
    // АЛДАА БИШ. Бүтээлтийн хувилбарт нэг л удаа ажиллана.
    // Хэрэв 2 удаа ажиллах нь бодит алдаа үүсгэж байвал (жишээ нь давхар
    // таймер) цэвэрлэгээний функц дутуу гэсэн үг — 3-р дасгалыг үз.
  }, []) // ← ХООСОН массив: зөвхөн анхны дүрслэлд

  // handlePlus — товч дарахад ажиллах функц. Зөвхөн count-ийг өөрчилнө.
  function handlePlus() {
    // Товч дарах бүрд:
    //   1) count өөрчлөгдөнө,
    //   2) React компонентыг дахин дуудна (re-render),
    //   3) ГЭХДЭЭ дээрх эффект дахин ажиллахгүй — учир нь [] хоосон.
    setCount((prev) => prev + 1)
  }

  return (
    <section className="card">
      <h2>Дасгал 1 — Анхны дүрслэл ба хоосон массив</h2>

      <p>
        Одоогийн тоо: <strong>{count}</strong>
      </p>

      <div className="row">
        {/* onClick={handlePlus} — ХААЛТГҮЙ функцийн ишлэл. Зөвхөн дарахад дуудагдана.
            onClick={handlePlus()} гэж хаалттай бичих нь буруу: дүрслэл бүрд
            шууд ажиллаж, төгсгөлгүй давталт үүсгэж болно. */}
        <button onClick={handlePlus}>+1 Нэмэх (төлөв солих)</button>
      </div>

      <h3>Эффектийн бүртгэл (console ба дэлгэц дээр)</h3>
      {/* Нөхцөлт жагсаалт: logs хоосон бол "товч дарна уу" гэж харуулна.
          Тернар оператор: нөхцөл ? үнэн үед : худал үед. */}
      {logs.length === 0 ? (
        <p className="note">Одоогоор бүртгэл алга — товч дарж үзээрэй.</p>
      ) : (
        <ul className="log-list">
          {/* map — logs-ийн элемент бүрээс <li> үүсгэнэ.
              index-ийг React-д key болгон өгнө (жагсаалт өөрчлөгдөхгүй тул
              энэ тохиолдолд болно). */}
          {logs.map((line, index) => (
            <li key={index}>{line}</li>
          ))}
        </ul>
      )}

      <p className="note">
        Товч дарах бүрд тоо нэмэгдэж, дэлгэц шинэчлэгдэж байна — ГЭВЧ бүртгэлд
        шинэ мөр НЭМЭГДЭХГҮЙ. Учир нь хамаарлын массив хоосон ([]) тул эффект
        зөвхөн анхны дүрслэл дээр нэг удаа ажиллана. Ингэж "нэг удаа" гэдгээ
        нүдээр батална.
      </p>

      <p className="note">
        Console-оос 2 мөр харагдаж байгаа бол StrictMode-ийн шалгалт (F5 дарахад
        шинээр). Бүтээлтэд нэг мөр л гарна.
      </p>
    </section>
  )
}
