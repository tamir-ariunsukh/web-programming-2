// 06-DepsForms.jsx — Дасгал 6: Хамаарлын массивын ГУРВАН хэлбэрийг харьцуулах
// Зорилго: нэг компонент дээр гурван эффект зэрэг бичээд, массивын хэлбэрээс
// эффектийн ажиллах ДАВТАМЖ хэрхэн өөрчлөгдөхийг console дээр шууд харьцуулах.
//
// Хамрах сэдэв: массив огт байхгүй / хоосон [] / утгатай [count] гэсэн
// 3 хэлбэр; төгсгөлгүй давталт яагаад үүсдэг вэ; объект хамаарлын алдаа.
//
// ЭНЭ ФАЙЛЫН ГОЛ ТЕХНИК: гурван эффект бүгд ЗӨВХӨН console.log хийнэ —
// ямар ч төлөв солихгүй. Яагаад? Учир нь "массивгүй" эффект дотор төлөв
// солих нь төгсгөлгүй давталт үүсгэдэг (доорх тайлбарыг үз). Зөвхөн
// console.log хийснээр аюулгүйгээр харьцуулж үзэх боломжтой.

import { useEffect, useState } from 'react'

export default function DepsForms() {
  // count — товчоор нэмэгдэх төлөв. Гол зорилго нь "шинэ дүрслэл (re-render)
  // үүсгэх": товч дарах бүрд 3 эффект харьцангуй яаж ажиллахыг ажиглана.
  const [count, setCount] = useState(0)

  // ---------- 1) МАССИВ ОГТ БАЙХГҮЙ ----------
  // useEffect(функц) — хоёр дахь аргумент өгөөгүй.
  // Утга: эффект ДҮРСЛЭЛ БҮРИЙН дараа ажиллана (анхны дүрслэл орсон).
  // Ихэнхдээ шаардлагагүй — өөрчлөгдөхгүй зүйлийг давтан хийсээр байна.
  useEffect(() => {
    console.log('① Массивгүй — дүрслэл бүрд ажиллана')
  })

  // ---------- 2) ХООСОН МАССИВ ----------
  // useEffect(функц, []) — хоосон массив.
  // Утга: эффект ЗӨВХӨН АНХНЫ дүрслэлд нэг удаа ажиллана.
  // Жишээ нь серверээс анхны өгөгдлийг татах ажилд тохирно (5-р дасгал).
  useEffect(() => {
    console.log('② Хоосон [] — зөвхөн анхны дүрслэлд нэг удаа')
  }, [])

  // ---------- 3) УТГАТАЙ МАССИВ ----------
  // useEffect(функц, [count]) — хянах утгуудын жагсаалт.
  // Утга: count ӨӨРЧЛӨГДӨХ БҮРД (ба анхны дүрслэлд) ажиллана.
  // React дүрслэл болгоны дараа count-ийг өмнөх утгатай Object.is-ээр
  // харьцуулж, өөрчлөгдсөн үед л эффектийг дахин ажиллуулна.
  useEffect(() => {
    console.log(`③ [count] — count өөрчлөгдсөн үед л (одоо: ${count})`)
  }, [count])

  // handlePlus — товч дарах бүрд count +1 → ШИНЭ дүрслэл (re-render).
  function handlePlus() {
    setCount((prev) => prev + 1)
  }

  return (
    <section className="card">
      <h2>Дасгал 6 — Хамаарлын массивын 3 хэлбэр</h2>

      <p>
        Одоогийн тоо: <strong>{count}</strong>
      </p>

      <div className="row">
        <button onClick={handlePlus}>+1 Нэмэх (шинэ дүрслэл үүсгэх)</button>
      </div>

      <h3>Хийх туршилт</h3>
      <ul>
        <li>
          F12 → Console-ийг нээ. Хуудас ачаалахад ① нэг, ② нэг, ③ нэг удаа
          хэвлэгдэнэ (StrictMode-той тул хөгжүүлэлтэд 2 дахин).
        </li>
        <li>
          "+1" товчийг дараа: ① дахин хэвлэгдэнэ (массивгүй нь дүрслэл бүрд),
          ② хэвлэгдэхгүй (нэг л удаа), ③ хэвлэгдэнэ (count өөрчлөгдсөн).
        </li>
        <li>
          Товч дарах бүрд ① мөрийн тоо хурдтай өсөж байгааг, ② нэг л байгааг
          харьцуулж үзээрэй — энэ бол давтамжийн бодит ялгаа.
        </li>
      </ul>

      <p className="note">
        ДҮРЭМ: эффект дотор ашигласан төлөв, props буюу тэдгээрээс бодогдсон
        утгыг хамаарлын массивт бичнэ. Дээрх ③ нь яг үүнийг хийж байна: count
        утгыг дотор нь ашиглаж байгаа тул [count] гэж бичсэн.
      </p>

      <p className="note">
        БУРУУ ЖИШЭЭ (ажиллуулж болохгүй — зөвхөн ойлголт):
        <br />
        <code>
          useEffect(() =&gt; &#123; setCount(count + 1); &#125;);
        </code>
        <br />— Массивгүй + дотор нь төлөв солих = ТӨГСӨГӨЛГҮЙ ДАВТАЛТ:
        эффект ажиллана → төлөв солигдоно → шинэ дүрслэл → эффект дахин
        ажиллана → ... зогсолтгүй.
      </p>

      <p className="note">
        ОБЪЕКТИЙН АЛДАА: хамаарлын массивт объект эсвэл функцийг шууд бичих
        нь түгээмэл алдаа. Учир нь тэдгээр дүрслэл бүрт ШИНЭЭР үүсч, "санах
        ойн хаяг" нь өөрчлөгддөг тул React ялгаагүй, эффект шаардлагагүйгээр
        давтагдана. Шийдэл: объектыг компонентын ГАДНА байлгах, эсвэл оронд
        нь энгийн утгуудыг (жишээ нь user.id) хамаарлын массивт бичих.
      </p>
    </section>
  )
}
