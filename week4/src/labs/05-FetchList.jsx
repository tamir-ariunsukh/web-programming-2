// 05-FetchList.jsx — Дасгал 5: Серверээс жагсаалт татах
// Зорилго (унших материалын "Дадлага 5"): серверээс жагсаалт татах эффект
// бичиж, ачаалал (loading) ба алдааны (error) төлөвийг дүрслэлд харуулах.
// Салгах үед хүсэлтийг цуцал (AbortController).
//
// Хамрах сэдэв: өгөгдөл/ачаалал/алдаа гэсэн 3 төлөв, async функцийг эффект
// дотор бичих дүрэм, AbortController ба цуцлалт, err.name !== 'AbortError'
// яагаад чухал вэ, "уралдааны нөхцөл" (race condition).
//
// ӨГӨГДЛИЙН ЭХ СУРВАЛЖ: week4/public/students.json файл.
// Vite dev server нь public/ доторх файлуудыг '/' замаар шууд үзүүлдэг тул
// fetch('/students.json') гэж дуудна (сервер, интернэт хэрэггүй).

import { useEffect, useState } from 'react'

export default function FetchList() {
  // ---------- ГУРВАН ТӨЛӨВ ----------
  // 1) students — ӨГӨГДЛИЙН төлөв: серверээс ирсэн хариу (объектын массив).
  const [students, setStudents] = useState([])

  // 2) loading — АЧААЛЛЫН төлөв: хүсэлт явагдаж байгаа эсэх.
  //    Анхны утга true — дэлгэцэнд гарах тэр мөчид хүсэлт эхэлж байгаа учир.
  const [loading, setLoading] = useState(true)

  // 3) error — АЛДААНЫ төлөв: алдаа гарвал текст, эс бөгөөс хоосон мөр ''.
  const [error, setError] = useState('')

  // reloadKey — "Дахин ачаалах" товчны төлөв (тоолуур).
  // Товч дарах бүрд 1-ээр нэмэгдэж, эффектийн хамаарал өөрчлөгдөж,
  // эффект ДАХИН ажиллана. Ингэж "төлвөөр эффект дахин ажиллуулах"
  // стандарт хэв маягийг үзүүлж байна.
  const [reloadKey, setReloadKey] = useState(0)

  // fail — туршилтын төлөв: чеклэгдсэн бол ЗОРИУДАА байхгүй файл руу
  // хүсэлт явуулж, АЛДААНЫ төлөвийг харуулна.
  const [fail, setFail] = useState(false)

  // useEffect — хамаарлын массивт [reloadKey, fail] гэсэн ХОЁР утга байна:
  // аль нэг нь өөрчлөгдөх бүрд (ба анхны дүрслэлд) эффект дахин ажиллана.
  useEffect(() => {
    // AbortController — хөтчийн built-in "цуцлах хэрэгсэл".
    // controller.signal-ийг fetch-д дамжуулбал, controller.abort() дуудахад
    // тухайн хүсэлт цуцлагдана. Яагаад хэрэгтэй вэ: хэрэглэгч хурдан цэс
    // соливол хуучин хүсэлт хожим буцаж ирээд шинэ өгөгдлийг дарж болно
    // (уралдааны нөхцөл). Цуцалбал ийм асуудал гарахгүй.
    const controller = new AbortController()

    // ЭФФЕКТИЙН ФУНКЦ ӨӨРӨӨ АСИНХРОН БАЙЖ БОЛОХГҮЙ.
    // Шалтгаан: async функц ҮРГЭЛЖ Promise буцаадаг бол React харин
    // цэвэрлэгээний ФУНКЦ хүлээдэг. Иймд дотор нь тусдаа async функц
    // тодорхойлоод дуудна; цэвэрлэгээг гадна түвшинд буцаана.
    async function load() {
      try {
        // Хүсэлт эхэллээ: ачааллын төлөвийг true, өмнөх алдааг цэвэрлэнэ.
        setLoading(true)
        setError('')

        // ТУРШИЛТИЙН АЛДАА: чеклэгдсэн бол fetch хийхгүйгээр зориуд алдаа
        // шиднэ. Бодит аппликейшнд ийм алдаа сервер 500 буцаах эсвэл
        // сүлжээ тасрах үед гардаг — алдааны төлөв хэрхэн харагдахыг үзүүлнэ.
        if (fail) {
          throw new Error('Сервер хариулахгүй байна (туршилт)')
        }

        // fetch(url, сонголтууд) — HTTP хүсэлт явуулна. Буцаах утга нь
        // Promise: await нь хариу ирэх хүртэл хүлээгээд response объектыг өгнө.
        // { signal: controller.signal } — цуцлах дохиог холбоно.
        const response = await fetch('/students.json', { signal: controller.signal })

        // response.ok — HTTP статус 200-299 хооронд бол true.
        // 404, 500 гэх мэт бол fetch ӨӨРӨӨ алдаа шиддэггүй тул бид шалгаж,
        // Error шидэж байна (catch рүү шилжинэ).
        if (!response.ok) {
          throw new Error(`Хариу ${response.status}`)
        }

        // response.json() — хариуны биеийг (JSON текст) JS объект болгож
        // хувиргана. Энэ ч гэсэн Promise тул await хийнэ. (JSON = JavaScript
        // Object Notation, энгийн утгын бичлэг.)
        const data = await response.json()

        // АМЖИЛТ: өгөгдлийг төлөвт бичиж, ачааллыг зогсооно.
        setStudents(data)
        setLoading(false)
      } catch (err) {
        // ЦУЦЛАЛТЫН АЛДААГ ХЭРЭГЛЭГЧИД ХАРУУЛАХГҮЙ:
        // abort() дуудахад fetch нь 'AbortError' нэртэй алдаа шиддэг.
        // Энэ бол ХЭВИЙН үйл явц (компонент арих/төлөв солигдох үед бид өөрсдөө
        // цуцалсан) тул алдааны төлөвт бичихгүй, шууд буцаана.
        // Мөн loading-ийг false болгохгүй: цуцлалтын дараа шинэ хүсэлт
        // ажиллаж байгаа бөгөөд түүнийг "ачаалж байна" төлвөөс гаргаж болохгүй.
        if (err.name === 'AbortError') return

        // БОДИТ алдаа (404, сүлжээ тасарсан гэх мэт) — алдааны төлөвт бичнэ.
        setError(`Өгөгдөл татаж чадсангүй: ${err.message}`)
        setLoading(false)
      }
    }

    // Тодорхойлсон async функцийг дуудна. (Promise буцаах ч энд await
    // хэрэггүй — дотооддоо төлвөө шинэчилнэ.)
    load()

    // ЦЭВЭРЛЭГЭЭ: эффект дахин ажиллахын өмнө эсвэл компонент арих үед
    // өмнөх хүсэлтийг цуцална. Ингэснээр хоцорсон хариу шинэ өгөгдлийг
    // дарж чадахгүй болно.
    return () => controller.abort()
  }, [reloadKey, fail]) // ← reloadKey эсвэл fail өөрчлөгдөх бүрд дахин ажиллана

  // ---------- НӨХЦӨЛТ ДҮРСЛЭЛ: төлөв бүрд тохирох харагдац ----------

  // АЧААЛЛЫН төлөв: хүсэлт явагдаж байхад зөвхөн энийг үзүүлнэ.
  // return нь функцийг ШУУД зогсоох тул доод хэсэг ажиллахгүй.
  if (loading) {
    return (
      <section className="card">
        <h2>Дасгал 5 — Өгөгдөл татах</h2>
        <p className="note">Ачаалж байна...</p>
      </section>
    )
  }

  // АЛДААНЫ төлөв: алдааны текст + "Дахин оролдох" товч.
  if (error) {
    return (
      <section className="card">
        <h2>Дасгал 5 — Өгөгдөл татах</h2>
        <p className="error">{error}</p>
        {/* Дахин оролдох: reloadKey-г 1-ээр нэмэхэд эффект дахин ажиллана.
            fail-ийг false болгож, зөв файл руу дахин хүсэлт явуулна. */}
        <button
          onClick={() => {
            setFail(false)
            setReloadKey((prev) => prev + 1)
          }}
        >
          Дахин оролдох
        </button>
      </section>
    )
  }

  // АМЖИЛТЫН төлөв: өгөгдлийн хүснэгт.
  return (
    <section className="card">
      <h2>Дасгал 5 — Өгөгдөл татах</h2>

      <div className="row">
        {/* Дахин ачаалах: reloadKey +1 → эффект дахин ажиллаж, шинэ хүсэлт
            явагдана (өмнөх нь cleanup дээр цуцлагдана). */}
        <button onClick={() => setReloadKey((prev) => prev + 1)}>
          Дахин ачаалах
        </button>

        {/* Алдааны туршилт: checkbox солигдоход fail нь хамаарлын массивт
            байгаа тул эффект автоматаар дахин ажиллана. */}
        <label className="check">
          <input
            type="checkbox"
            checked={fail}
            onChange={(event) => setFail(event.target.checked)}
          />
          Алдаа турших (зориуд алдаа үүсгэнэ)
        </label>
      </div>

      <table className="table">
        <thead>
          <tr>
            {/* Хүснэгтийн толгой мөр. <th> — толгойн нүд. */}
            <th>#</th>
            <th>Нэр</th>
            <th>Анги</th>
            <th>Оноо</th>
          </tr>
        </thead>
        <tbody>
          {/* map — students массивын элемент бүрээс <tr> мөр үүсгэнэ.
              key={student.id} — React-д мөрүүдийг таних давтагдашгүй утга. */}
          {students.map((student) => (
            <tr key={student.id}>
              <td>{student.id}</td>
              <td>{student.name}</td>
              <td>{student.grade}</td>
              <td>{student.score}</td>
            </tr>
          ))}
        </tbody>
      </table>

      <p className="note">
        Өгөгдөл локал файлаас ирдэг тул маш хурдан — "Ачаалж байна" төлөв
        агшин зуур өнгөрнө. Удаан ачааллыг үзэхийн тулд F12 → Network →
        "Slow 3G" сонгоод "Дахин ачаалах" дарж үзээрэй.
      </p>

      <p className="note">
        Хэрэв хүсэлт явах зуур цэсийг сольж, явах юм бол эффектийн цэвэрлэгээ
        хүсэлтийг ЦУЦАЛНА (AbortController) — хоцорсон хариу шинэ төлөвийг
        дарахгүй. Цуцлалтын алдаа нь хэвийн учир хэрэглэгчид харагдахгүй.
      </p>
    </section>
  )
}
