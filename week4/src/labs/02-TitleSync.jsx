// 02-TitleSync.jsx — Дасгал 2: Утгатай хамаарлын массив
// Зорилго (унших материалын "Дадлага 2"): хамаарлын массивт НЭГ УТГА зааж,
// зөвхөн тухайн утга өөрчлөгдөхөд хөтчийн гарчгийг (document.title) шинэчлэх.
//
// Хамрах сэдэв: useEffect-ийн 2 дахь аргумент утгатай байх үеийн зан төлөв,
// гаж нөлөө (дэлгэцээс гадна зүйл болох хөтчийн табд бичих), цэвэрлэгээ.

import { useEffect, useState } from 'react'

export default function TitleSync() {
  // count — гарчигт орох утга. Энэ утга өөрчлөгдөх БҮРД эффект ажиллана.
  const [count, setCount] = useState(0)

  // name — ЗОРИУДАА эффектэд хамааралгүй хоёр дахь төлөв.
  // Зорилго: "хамааралгүй төлөв өөрчлөгдөхөд эффект ажиллахгүй" гэдгийг
  // харуулах. Нэр бичиж үзэхэд гарчиг ХӨДЛӨХГҮЙ байх болно.
  const [name, setName] = useState('')

  // useEffect — 2 дахь аргумент нь [count] буюу УТГАТА массив.
  //
  // ДҮРЭМ (React дотооддоо Object.is-ээр харьцуулдаг):
  //   React дүрслэл болгоны дараа массивын утгуудыг өмнөх дүрслэлийнхтэй
  //   харьцуулна. count өөрчлөгдсөн бол эффект дахин ажиллана, өөрчлөгдөөгүй
  //   бол алгасагдана.
  //   → count = утгаараа харьцуулагдах энгийн тоо тул асуудалгүй.
  //   (Харин объект, массив байвал санах ойн хаягаараа харьцуулагддаг тул
  //    дүрслэл бүрд шинээр үүсвэл эффект шаардлагагүйгээр давтагдана.)
  useEffect(() => {
    // document.title — хөтчийн ТАБЫН гарчиг. Энэ бол "гадна систем":
    // React-ийн зурдаг <div id="root">-оос ГАДНА орших зүйл. Тиймээс
    // үүнийг дүрслэлийн үед биш, ЭФФЕКТ дотор шинэчилнэ.
    //
    // Template literal: `...${count}...` — арын хашилт дотор ${ } хаалтаар
    // хувьсагчийн утгыг текстэн дунд оруулж бичнэ.
    document.title = `Тоо: ${count}`

    // ЦЭВЭРЛЭГЭЭНИЙ ФУНКЦ — эффектээс функцийг буцааж өгвөл React түүнийг:
    //   1) эффект ДАХИН ажиллахын өмнө (өмнөх ажлыг цэвэрлэхээр),
    //   2) компонент дэлгэцээс арих үед (хамгийн сүүлд нэг удаа)
    // дуудна.
    // Энд: цэс солигдож энэ компонент арихад гарчгийг анхны утга руу нь
    // буцаана. Ингэхгүй бол "Тоо: 5" гэсэн гарчиг наалдаад үлдэнэ.
    return () => {
      document.title = 'Week 4 — useEffect ба амьдралын мөчлөг (лаборатор)'
    }
  }, [count]) // ← УТГАТА массив: count өөрчлөгдөх бүрд (ба анхны дүрслэлд)

  return (
    <section className="card">
      <h2>Дасгал 2 — Хөтчийн гарчиг ба утгатай массив</h2>

      <p>
        {/* {count} — төлвийн утгыг дэлгэцэнд бичнэ. */}
        Гарчиг өөрчлөгдөх тоо: <strong>{count}</strong>
      </p>

      <div className="row">
        {/* Функциональ шинэчлэл: prev нь React-ийн өгч буй өмнөх утга. */}
        <button onClick={() => setCount((prev) => prev + 1)}>+1 Нэмэх</button>
        <button onClick={() => setCount((prev) => prev - 1)}>−1 Хасах</button>
        <button onClick={() => setCount(0)}>0 болгох</button>
      </div>

      <h3>Хамааралгүй төлөв (туршилт)</h3>
      <div className="row">
        {/* Хяналттай оролт: value нь төлвөөс, onChange бүрд setState.
            Энд setState нь дүрслэл ДАХИН дуудагдахыг үүсгэнэ — гэвч
            эффект [count] учир count хөдлөөгүй бол ажиллахгүй. */}
        <input
          type="text"
          value={name}
          placeholder="Нэр бичээд үзээрэй..."
          onChange={(event) => setName(event.target.value)}
        />
        <span className="mono">Нэр: {name === '' ? '(хоосон)' : name}</span>
      </div>

      <h3>Одоогийн хөтчийн гарчиг</h3>
      <p>
        {/* Гарчгийн утгыг дэлгэцэн дээр ч харуулж байна — таб дээрхтэй
            ижил байгааг нүдээр харьцуулахад амар. */}
        <span className="mono">Тоо: {count}</span>
      </p>

      <p className="note">
        Хөтчийнхөө ТАБЫГ хараарай: тоо нэмэгдэх бүрд гарчиг шинэчлэгдэнэ.
        Харин нэрийн талбарт бичихэд төлөв өөрчлөгдөж, дэлгэц шинэчлэгдэж
        байгаа ч гарчиг ХӨДЛӨХГҮЙ — учир нь хамаарлын массивт зөвхөн count
        байна. Энэ бол "хамаарлын массив яг зөв утгыг л хянадаг" гэдгийн
        баталгаа.
      </p>
    </section>
  )
}
