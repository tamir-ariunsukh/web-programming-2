// 04-WindowSize.jsx — Дасгал 4: Цонхны хэмжээ сонсох ба сонсогчийн цэвэрлэгээ
// Зорилго (унших материалын "Дадлага 4"): цонхны хэмжээг сонсож, өргөнийг
// төлөвт хадгалах. Сонсогчийг (event listener) цэвэрлэхээ МАРТАХГҮЙ.
//
// Хамрах сэдэв: addEventListener / removeEventListener, яагаад "нэмсэнтэй
// ИЖИЛ заалтаар" салгах ёстой вэ, давхар сонсогчийн асуудал.

import { useEffect, useState } from 'react'

export default function WindowSize() {
  // АНХНЫ УТГА нь window.innerWidth / window.innerHeight.
  // window — хөтчийн built-in объект (цонх). innerWidth нь одоогийн
  // харагдах хэсгийн өргөн (пикселээр).
  // Анхны утгыг шууд эндээс авснаар жинхэнэ хэмжээгээр эхэлнэ.
  const [width, setWidth] = useState(window.innerWidth)
  const [height, setHeight] = useState(window.innerHeight)

  // useEffect — хоосон массивтай: сонсогчийг ЗӨВХӨН нэг удаа (анхны
  // дүрслэлд) нэмнэ. Хэмжээ өөрчлөгдөх бүрд СОНСОГЧ ажиллаж төлөв солих тул
  // эффектийг дахин ажиллуулах шаардлагагүй.
  useEffect(() => {
    // handleResize — сонсогчийн функц. Цонхны хэмжээ өөрчлөгдөх бүрд
    // хөтөч үүнийг дуудна.
    //
    // ЯАГААД ЭФФЕКТИЙН ДОТОР ТОДОРХОЙЛОВ? Учир нь энэ функцийг
    //   (1) addEventListener-д нэмэх, (2) removeEventListener-ээс салгах
    // хоёрт ЯГ НЭГ ИЖИЛ функцийг хэрэглэх шаардлагатай.
    // addEventListener/removeEventListener нь функцыг ИШЛЭЛЭЭР (санах ойн
    // хаягаар) ялгадаг: өөр эсвэл шинээр үүсгэсэн функц өгвөл салгаж чадахгүй,
    // сонсогч давхарлан үлдэнэ. Эффект дотор тодорхойлсноор нэг л заалт
    // үүсэж, cleanup яг түүнийгээ л салгана.
    function handleResize() {
      // Дэлгэцийн хэмжээний шинэ утгуудыг төлөвт бичнэ.
      // Төлөв солигдох бүрд React дахин дүрсэлнэ.
      setWidth(window.innerWidth)
      setHeight(window.innerHeight)
    }

    // addEventListener('resize', ...) — 'resize' үйл явдалд (цонхны хэмжээ
    // өөрчлөгдөх) сонсогч бүртгэнэ. Энэ бол "гадна систем"-тэй синхрончлол:
    // компонент хөтчийн цонхыг "сонсож" эхэлж байна.
    window.addEventListener('resize', handleResize)

    // ЦЭВЭРЛЭГЭЭНИЙ ФУНКЦ — ижил үйл явдал, ижил функцээр салгана.
    // Хэрэв салгахгүй бол: цэс солих бүрд шинэ сонсогч нэмэгдэж, нэг resize
    // үйл явдал ОЛОН удаа боловсруулагдана (давхар ажиллагаа) — мөн устгасан
    // компонентын setState-ийг дуудаж алдаа/нөөцийн алдагдал үүсгэнэ.
    return () => window.removeEventListener('resize', handleResize)
  }, []) // ← ХООСОН массив: сонсогчийг нэг л удаа нэмнэ

  return (
    <section className="card">
      <h2>Дасгал 4 — Цонхны хэмжээ ба сонсогчийн цэвэрлэгээ</h2>

      {/* Төлвийн утгуудыг харуулна. Цонхны хэмжээг өөрчлөх бүрд
          сонсогч ажиллаж, эдгээр тоо амьдаар шинэчлэгдэнэ. */}
      <p>
        Өргөн: <span className="big">{width}px</span>
      </p>
      <p>
        Өндөр: <span className="big">{height}px</span>
      </p>

      <p className="note">
        Цонхныхоо хэмжээг өөрчилж (эсвэл F12-оор төхөөрөмжийн харагдац
        сольж) үзээрэй — тоонууд амьдаар шинэчлэгдэнэ. Энэ бол resize
        үйл явдал → handleResize → setWidth → дахин дүрслэл гэсэн гинжин
        холбоо юм.
      </p>

      <p className="note">
        ОДОО ЗОРИУДАА ТУРШИЖ ҮЗЭЭРЭЙ: цэвэрлэгээний мөрийг (return ...) түр
        NULL болгож, ноорог бичиж хадгалаад, цэсийг сольж нааш цааш хөдөлгө.
        Дараа нь Console дээр resize үйл явдал давхарлан олон удаа ажиллаж
        байгааг хараад, цэвэрлэгээгээ буцааж зааж өгөөрэй.
      </p>
    </section>
  )
}
