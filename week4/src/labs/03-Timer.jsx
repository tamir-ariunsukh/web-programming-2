// 03-Timer.jsx — Дасгал 3: Секунд тутам өсдөг тоолуур ба цэвэрлэгээ
// Зорилго (унших материалын "Дадлага 3"): секунд тутам өсдөг тоолуур бичиж,
// компонент дэлгэцээс арих үед таймерыг цэвэрлэх.
//
// Хамрах сэдэв: setInterval ба clearInterval, цэвэрлэгээний функц (cleanup),
// цэвэрлэгээ хэзээ дуудагдах, хуучин утгад хүлэгдэх асуудал (stale closure),
// компонентыг салгах (unmount) ба нөөцийн алдагдал.

import { useEffect, useState } from 'react'

// ---------- Дотоод компонент 1: секундийн тоолуур ----------
// Энэ компонент дэлгэцэнд гармагц (mount) таймер эхлүүлж, арих үедээ
// (unmount) таймерээ зогсооно. Үүнийг ДОТООД компонент болгосноор
// "харуулах / нуух" товчоор mount ↔ unmount-ийг бодитоор үүсгэж үзнэ.

function SecondsCounter() {
  // seconds — өнгөрсөн секундийн тоо (төлөв).
  const [seconds, setSeconds] = useState(0)

  // useEffect — хоосон массивтай: зөвхөн анхны дүрслэлд ажиллаж,
  // таймерыг НЭГ удаа эхлүүлнэ. Мөн цэвэрлэгээний функцийг буцаана.
  useEffect(() => {
    console.log('Таймер эхэллээ (эффект ажиллалаа)')

    // setInterval(функц, хугацаа) — хөтчийн built-in функц: заасан
    // хугацаа (миллисекунд) тутамд өгсөн функцийг давтан дуудна.
    // Буцах утга нь "таймерын дугаар" (id) — дараа нь зогсооход хэрэглэнэ.
    const id = setInterval(() => {
      // ФУНКЦИОНАЛЬ ШИНЭЧЛЭЛ: setSeconds(prev => prev + 1).
      //
      // ЯАГААД? Хамаарлын массив хоосон тул энэ эффект дахин ажиллахгүй.
      // Хэрэв setSeconds(seconds + 1) гэж бичвэл `seconds` нь эффект
      // ажиллах үеийн АНХНЫ утга (0) дээрээ "хүлэгдэж" үлдэж, тоо
      // үргэлж 1 л болно. Энийг хуучин утгад хүлэгдэх (stale closure) гэнэ.
      // Харин prev хэлбэрээр бичихэд React ХАМГИЙН СҮҮЛИЙН утгыг өгдөг
      // тул дараалан дуудсан ч зөв ажиллана.
      setSeconds((prev) => prev + 1)
    }, 1000) // 1000 мс = 1 секунд

    // ЦЭВЭРЛЭГЭЭНИЙ ФУНКЦ — эффектээс функцийг буцаана.
    // React үүнийг 2 үед дуудна:
    //   1) эффект дахин ажиллахын өмнө (энд хоосон массив тул давтагдахгүй),
    //   2) энэ компонент дэлгэцээс АРИХ үед (unmount) — "Нуух" товч дарахад.
    return () => {
      console.log('Цэвэрлэгээ: таймер зогслоо')
      // clearInterval(id) — дээрх таймерыг зогсооно. Ингэхгүй бол таймер
      // дэвсгэрт үүрд ажилласаар санах ой эзэлнэ (нөөцийн алдагдал).
      // Анхаар: ЦЭВЭРЛЭГЭЭ зөвхөн ӨӨРИЙН эхлүүлсэн ажлаа зогсооно.
      clearInterval(id)
    }
  }, []) // ← ХООСОН массив: таймер зөвхөн нэг удаа эхэлнэ

  return (
    <p className="big">
      {/* {seconds} — секунд тутам React автоматаар дахин дүрсэлнэ. */}
      ⏱ {seconds} секунд
    </p>
  )
}

// ---------- Үндсэн компонент: харуулах / нуух ----------

export default function Timer() {
  // show — дотоод тоолуурыг дэлгэцэнд харуулах эсэх. true бол доорх
  // нөхцөлт дүрслэл <SecondsCounter />-ыг монтажлана (mount), false бол
  // арилгана (unmount) — цэвэрлэгээний функцийг ажиллуулна.
  const [show, setShow] = useState(true)

  // handleToggle — товч дарахад show-ийг эсрэг утга руу нь эргүүлнэ.
  // !prev — логик үгүйсгэлт: true → false, false → true.
  function handleToggle() {
    setShow((prev) => !prev)
  }

  return (
    <section className="card">
      <h2>Дасгал 3 — Секундийн тоолуур ба цэвэрлэгээ</h2>

      <div className="row">
        {/* Тернар оператор: show үнэн бол "нуух", худал бол "харуулах" гэж
            товчны текст солигдоно. */}
        <button onClick={handleToggle}>
          {show ? 'Таймерыг НУУХ (салгах)' : 'Таймерыг ХАРУУЛАХ (холбох)'}
        </button>
      </div>

      {/* НӨХЦӨЛТ ДҮРСЛЭЛ: show === true үед л <SecondsCounter /> байна.
          false болгоход React компонентыг бүрэн салгаж (unmount) —
          дээрх эффектийн return доторх цэвэрлэгээ ажиллана.
          Дахин true болгоход шинэ компонент шинээр монтажлагдаж,
          seconds төлөв 0-ээс эхэлнэ. */}
      {show && <SecondsCounter />}

      <p className="note">
        ТУРШИЛТ: Console-ийг нээгээд "Нуух" товч дарахад "Цэвэрлэгээ: таймер
        зогслоо" гэж хэвлэгдэхийг хараарай. Дахин "Харуулах" дарахад шинэ
        таймер эхэлж, тоо 0-ээс эхэлнэ — өмнөх таймер зогссон тул хоёр
        таймер зэрэг ажиллахгүй.
      </p>

      <p className="note">
        Хэрэв цэвэрлэгээгүй бол: "Нуух" дарсан ч таймер дэвсгэрт ажилласаар
        байж, дахин "Харуулах" бүрд нэг нэмэгдэнэ — нэг секундэд хэд хэдэн
        тоо нэмэгдэх "давхар ажиллагаа" үүснэ. Хөгжүүлэлтийн горимд StrictMode
        мөн эффектийг 2 удаа ажиллуулж үздэг: зөв цэвэрлэгээтэй бол ямар ч
        асуудал гарахгүй.
      </p>
    </section>
  )
}
