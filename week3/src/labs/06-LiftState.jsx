// 06-LiftState.jsx — Дадлага 6: Төлөвийг дээш өргөх (lifting state up)
// Хичээлийн 5-р бүлэг: хамтын төлөвийг хамгийн ойрын ДУНДЫН ЭЦЭГ дээр байрлуулна.
//   Эцэг нь: (1) төлөвийн утгыг props-оор дамжуулна,
//            (2) шинэчлэх функцийг "буцаан дуудах функц" хэлбэрээр дамжуулна.
//   Хүү нь үйл явдал болоход тэр функцийг дуудаж, шинэ утгыг эцэг рүү буцаана.

import { useState } from 'react'

// ---------- ХҮҮ КОМПОНЕНТ 1: товч ----------
// Хүү компонент ӨӨРИЙН ТӨЛӨВГҮЙ. props-оос label (текст) ба onStep (функц) авна.
// props нь ЗӨВХӨН УНШИХ — хүү дотор шууд өөрчлөх боломжгүй.
// { label, onStep } — объектын задлалт: props.label, props.onStep гэсэнтэй ижил.
function StepButton({ label, onStep }) {
  return (
    // onClick={onStep} — хүү дээр дарахад ЭЦГЭЭС ирсэн функцийг дуудна.
    // Функц нь эцэг дээр ажиллаж, эцгийн төлөвийг шинэчилнэ.
    // onStep гэх нэр нь "onXxx" хэлбэртэй байх нь React-ийн нийтлэг хэв маяг.
    <button onClick={onStep}>{label}</button>
  )
}

// ---------- ХҮҮ КОМПОНЕНТ 2: зөвхөн харуулах ----------
// Энэ хүү ямар ч үйл явдалгүй — зөвхөн prop-оор ирсэн утгыг харуулна.
function Display({ value }) {
  return (
    <p className="note">
      Дэлгэц дээрх утга (props.value): <strong>{value}</strong>
    </p>
  )
}

// ---------- ЭЦЭГ КОМПОНЕНТ: төлөвийг эзэмшинэ ----------
export default function LiftState() {
  // Төлөв ЭНД (эцэг дээр) байрлана — хэд хэдэн хүү хамтран ашиглана.
  // Ах дүү компонентууд шууд өгөгдөл солилцож чадахгүй (өгөгдөл нэг чиглэлд,
  // дээрээс доош урсдаг) тул хамтын төлөвийг дундын эцэг дээр тавьдаг.
  const [count, setCount] = useState(0)

  return (
    <section className="card">
      <h2>Дадлага 6 — Төлөвийг дээш өргөх</h2>

      <p>
        Эцэг дээрх тоо: <strong>{count}</strong>
      </p>

      <div className="row">
        {/* Утга (count) ба шинэчлэх функц хоёулаа props-оор ДООШОО урсана.
            onStep={() => setCount((prev) => prev + 1)} — сумтай функц нь
            зөвхөн хүү дээр ДАРАГДАХ үед эцэг дээр ажиллана. */}
        <StepButton label="+1" onStep={() => setCount((prev) => prev + 1)} />

        <StepButton label="−1" onStep={() => setCount((prev) => prev - 1)} />

        {/* Өмнөх утгаас хамааралгүй тул шууд утга өгч болно. */}
        <StepButton label="0 болгох" onStep={() => setCount(0)} />

        {/* Мөн шинэ утгыг бодож гаргах жишээ (дамжуулагч функц):
            эцэг дээр тооцоолол хийгдэж байгааг анхаар. */}
        <StepButton label="+10" onStep={() => setCount((prev) => prev + 10)} />
      </div>

      {/* ИЖИЛ төлөвийг хоёр дахь хүү рүү дамжуулж байна:
          аль ч хүү дээр үйлдэл болоход ХОЁУЛАА шинэ утгыг харна. */}
      <Display value={count} />

      <p className="note">
        Гол санаа: төлөв нэг эх сурвалжид (эцэг дээр) байх нь өгөгдлийн урсгалыг
        таамаглахад хялбар болгодог. Хүү нь төлөвийг өөрөө эзэмшихгүй — зөвхөн
        буцаан дуудах функцээр "хүсэлт" илгээнэ.
      </p>
    </section>
  )
}
