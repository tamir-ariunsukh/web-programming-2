// 01-Counter.jsx — Дадлага 1: Тоолуур (useState-ийн хамгийн энгийн жишээ)
// Хичээлийн 1-р бүлэг: төлөв (state) гэж юу вэ, useState-ийн синтакс,
// шинэчлэх функц, функциональ шинэчлэл, hook-ийн дүрэм.

// import — зөвхөн хэрэгтэй hook-оо нэрээр нь авна (react багцаас).
import { useState } from 'react'

// Компонент гэдэг нь ТОМ үсгээр эхэлсэн нэртэй, JSX буцаадаг энгийн функц.
// export default — энэ файлын үндсэн экспорт; App.jsx үүнийг импортолж хэрэглэнэ.
export default function Counter() {
  // useState(0) гэдгийн утга:
  //   1) Төлөв үүсгэж, АНХНЫ утгыг 0 гэж өгнө (анхны утга зөвхөн эхний дүрслэлд хэрэглэгдэнэ).
  //   2) ЯГ 2 элементтэй массив буцаана: [одоогийн утга, шинэчлэх функц].
  //   3) Массивын задлалт (destructuring) — эхний элементийг count гэж,
  //      хоёр дахь элементийг (шинэчлэх функц) setCount гэж салгаж авна.
  //   4) set угтвартай нэр — React-ийн нийтлэг хэв маяг: count / setCount.
  //   5) Hook-ийг ЗААВАЛ функцийн хамгийн дээд түвшинд дуудна:
  //      if, for, дотоод функц дотор дуудаж БОЛОХГҮЙ (React дарааллаар нь ялгадаг).
  const [count, setCount] = useState(0)

  // Үйл явдлын функц. Зөвхөн товч ДАРАГДАХ үед ажиллана (дүрслэл бүрд биш).
  function handlePlus() {
    // ФУНКЦИОНАЛЬ ШИНЭЧЛЭЛ: setCount((prev) => prev + 1).
    // prev нь React-ийн өгч буй "өмнөх утга". Дараалан 2 удаа дуудсан ч зөв ажиллана
    // (setCount(count + 1) гэж бичвэл хуучин count-оос бодож, алдаа гарч болзошгүй).
    setCount((prev) => prev + 1)
  }

  function handleMinus() {
    // Тернар оператор: утга 0 бол 0 хэвээр, эс бөгөөс 1-ээр хасна.
    // Ингэснээр тоо сөрөг болохгүй.
    setCount((prev) => (prev === 0 ? 0 : prev - 1))
  }

  function handleReset() {
    // Өмнөх утгаас хамааралгүй үед шинэ утгыг ШУУД өгч болно.
    setCount(0)
  }

  // return дотор JSX бичнэ: HTML шиг харагдах боловч дотор нь { } хаалтаар
  // JS илэрхийлэл (хувьсагч, тооцоолол, функц) бичих боломжтой.
  return (
    <section className="card">
      {/* className — HTML-ийн class атрибут. JS дотор 'class' нь нөөц үг тул className гэнэ. */}
      <h2>Дадлага 1 — Тоолуур</h2>

      <p>
        {/* {count} — төлөвийн утгыг дэлгэцэнд бичнэ.
            count хэзээ нэгэн цагт өөрчлөгдвөл React энэ компонентыг автоматаар дахин дүрсэлнэ. */}
        Одоогийн тоо: <strong>{count}</strong>
      </p>

      <div className="row">
        {/* onClick={handlePlus} — ХААЛТГҮЙ функцийн ишлэл.
            Зөвхөн дарахад л дуудагдана.
            onClick={handlePlus()} гэж ХААЛТТАЙ бичих нь буруу:
            дүрслэл бүрд шууд ажиллаж, төгсгөлгүй давталт үүсгэж болно. */}
        <button onClick={handlePlus}>+1 Нэмэх</button>

        {/* disabled — төлвөөс шууд хамаарах атрибут: count 0 үед товч идэвхгүй болно. */}
        <button onClick={handleMinus} disabled={count === 0}>
          −1 Хасах
        </button>

        <button onClick={handleReset}>0 болгох</button>
      </div>

      <p className="note">
        ЧУХАЛ: энгийн хувьсагч (жишээ нь <code>let count = 0</code>) ашиглавал утга нь
        өөрчлөгдсөн ч React дахин дүрслэхээр шийдэхгүй тул дэлгэц хуучин хэвээр үлдэнэ.
        Тиймээс дэлгэц дээр өөрчлөгддөг БҮХ утгыг төлөвт хадгална.
      </p>

      <p className="note">
        Hook-ийн дүрэм: useState-ийг функцийн хамгийн дээд түвшинд, үргэлж ижил
        дарааллаар дуудна. Нөхцөл, давталт, дотоод функц дотор дуудвал төлөв холилдож,
        алдаа гарна.
      </p>
    </section>
  )
}
